// build.mjs: lay the ten scenes on the clock and write video/data/timing.js + video/index.html.
//   node tools/build.mjs
// Each scene's narration comes from narration/audio/final/sNN.{mp3,json} (or narration/audio/sNN.* before any
// post-processing). A scene without narration yet gets placeholder word times at the voice samples' pace, so the
// scenes can be built and checked before the full take; rerunning after the take retimes every cue.
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from "node:fs";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { ROOT, scenes, say } from "../narration/script.mjs";

const LEAD = 0.7, TAIL = 1.1, XFADE = 0.8;      // seconds: silence before / after each scene's voice, crossfade
const PACE = 2.9, COMMA = 0.25, STOP = 0.45;    // placeholder: words per second, pause after , and .
const V = join(ROOT, "video");

function placeholder(text) {
  let t = 0;
  return say(text).split(/\s+/).map(w => {
    const s = t; t += 1 / PACE;
    const e = t; t += /[.?!:]$/.test(w) ? STOP : /[,;]$/.test(w) ? COMMA : 0;
    return { w, s: +s.toFixed(3), e: +e.toFixed(3) };
  });
}

mkdirSync(join(V, "assets/audio"), { recursive: true });
let start = 0, real = 0;
const out = scenes().map(sc => {
  const id = `s${String(sc.n).padStart(2, "0")}`;
  const src = [join(ROOT, "narration/audio/final", id), join(ROOT, "narration/audio", id)].find(p => existsSync(`${p}.json`));
  let words, audio = null, media = null;
  if (src) {
    words = JSON.parse(readFileSync(`${src}.json`, "utf8")).words.map(w => ({ w: w.word, s: w.start, e: w.end }));
    audio = `assets/audio/${id}.mp3`;
    copyFileSync(`${src}.mp3`, join(V, audio));
    media = +execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", `${src}.mp3`]).toString().trim();
    real++;
  } else words = placeholder(sc.text);
  const speech = words.at(-1).e;
  const s = { n: sc.n, id, title: sc.title, start: +start.toFixed(3), lead: LEAD, speech: +speech.toFixed(3),
              dur: +(LEAD + speech + TAIL).toFixed(3), audio, media, words };
  start += s.dur - XFADE;
  return s;
});
const last = out.at(-1);
last.dur = +(last.dur + 5.0).toFixed(3);                        // room for the credits and the closing fade
const total = +(last.start + last.dur).toFixed(3);
writeFileSync(join(V, "data/timing.js"), "window.TIMING = " + JSON.stringify({ total, placeholder: real < out.length, scenes: out }) + ";\n");

// music bed: full between voices, ducked under them (times from the clip's start, which is 0)
const music = existsSync(join(V, "assets/audio/music.wav"));
const pts = [{ t: 0, v: 0.55 }];
for (const s of out) {
  const a = s.start + s.lead, b = a + s.speech;
  pts.push({ t: +(a - 0.5).toFixed(2), v: 0.45 }, { t: +(a - 0.05).toFixed(2), v: 0.11 }, { t: +(b + 0.15).toFixed(2), v: 0.11 }, { t: +(b + 0.9).toFixed(2), v: 0.4 });
}
pts.push({ t: +(total - 3).toFixed(2), v: 0.45 }, { t: total, v: 0 });
const automation = JSON.stringify({ version: 1, lanes: [{ target: "volume", points: pts }] }).replace(/"/g, "&quot;");

const f = x => x.toFixed(3);
const html = `<!doctype html>
<!-- generated by tools/build.mjs: edit the scenes in compositions/, not this file -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <link rel="stylesheet" href="lib/fl.css" />
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1920px; height: 1080px; overflow: hidden; background: var(--canvas); }
      #root { position: relative; width: 1920px; height: 1080px; background: var(--canvas); }
      #bg { position: absolute; inset: 0; background: radial-gradient(ellipse 70% 60% at 50% 45%, #13151c 0%, var(--canvas) 70%); }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${f(total)}" data-width="1920" data-height="1080">
      <div id="bg" class="clip" data-start="0" data-duration="${f(total)}" data-track-index="0"></div>
${out.map((s, i) => `      <div id="${s.id}" class="clip" data-composition-id="${s.id}" data-composition-src="compositions/${s.id}.html" data-start="${f(s.start)}" data-duration="${f(s.dur)}" data-track-index="${1 + (i % 2)}" data-width="1920" data-height="1080" style="z-index:${i + 1}"></div>`).join("\n")}
${out.filter(s => s.audio).map(s => `      <audio id="vo-${s.id}" src="${s.audio}" data-start="${f(s.start + s.lead)}" data-duration="${f(s.media)}" data-track-index="3" data-volume="1"></audio>`).join("\n")}
${music ? `      <audio id="music" src="assets/audio/music.wav" data-start="0" data-duration="${f(total)}" data-track-index="4" data-volume="1" data-automation="${automation}"></audio>` : "      <!-- music: assets/audio/music.wav not made yet -->"}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
writeFileSync(join(V, "index.html"), html);
console.log(`${out.length} scenes, ${real} with narration, total ${Math.floor(total / 60)}:${(total % 60).toFixed(1).padStart(4, "0")}`);
for (const s of out) console.log(`  ${s.id} ${s.title.padEnd(22)} start ${f(s.start).padStart(8)}  dur ${f(s.dur).padStart(7)}  speech ${f(s.speech)}`);
